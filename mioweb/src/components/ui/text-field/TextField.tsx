import { Field } from '@ark-ui/solid/field';
import {
  children as resolveChildren,
  createSignal,
  createUniqueId,
  Match,
  onCleanup,
  onMount,
  Show,
  splitProps,
  Switch,
  untrack,
  type Component,
  type JSX,
} from 'solid-js';
import { Icon } from '../icon/Icon';
import { IconButton } from '../buttons/icon-button/IconButton';
import styles from './text-field.module.css';

export type TextFieldVariant = 'filled' | 'outlined';

type Control = HTMLInputElement | HTMLTextAreaElement;

type Common<T extends Control> = {
  /** Default `filled`. Don't mix both variants in one form. */
  variant?: TextFieldVariant;
  /** Visible label and accessible name. Every field needs one; keep it short, one line. */
  label?: string;
  /** Helper line below the field. Replaced by the error text while invalid. */
  supportingText?: JSX.Element;
  /** Error message shown under the field; makes the field invalid unless `invalid` says otherwise. */
  errorText?: JSX.Element;
  /** Manual invalid state. Defaults to `true` when there is an error text (own or native). */
  invalid?: boolean;
  /** Show an error icon at the end while invalid when there's no `trailing`. Default true. */
  errorIcon?: boolean;
  required?: boolean;
  disabled?: boolean;
  /** Focusable, not editable. Say so in the label or supporting text. */
  readOnly?: boolean;
  /** Character limit; with `counter`, shows `used/limit` under the field. */
  maxLength?: number;
  counter?: boolean;
  /** Static text before / after the input (currency, unit, domain). */
  prefixText?: string;
  suffixText?: string;
  /** Spoken form of the prefix / suffix ("Euro", "at gmail dot com"). */
  prefixLabel?: string;
  suffixLabel?: string;
  /** A 24px icon (`<Icon />`) or an icon button at the start. */
  leading?: JSX.Element;
  /** A 24px icon or an icon button (visibility toggle, menu) at the end. */
  trailing?: JSX.Element;
  /** Clear button at the end while the field has text (and no `trailing` or error icon). */
  clearable?: boolean;
  /** Accessible name of the clear button. Default "Clear". */
  clearLabel?: string;
  /** Controlled value. Pair with `onValueChange` (or `onInput`). */
  value?: string;
  /** Initial value when uncontrolled. */
  defaultValue?: string;
  onValueChange?: (value: string) => void;
  /** Reduced height (48px). Opt-in only: below the 56px default target. */
  dense?: boolean;
  /** Id of the input. Generated by default. */
  id?: string;
  /** Classes for the root element (sets width; the field fills it). */
  class?: string;
  style?: JSX.CSSProperties;
  /** The native input or textarea: focus(), select(), setCustomValidity(), ... */
  ref?: T | ((el: T) => void);
  onInput?: JSX.EventHandlerUnion<T, InputEvent>;
  onFocus?: JSX.EventHandlerUnion<T, FocusEvent>;
  onBlur?: JSX.EventHandlerUnion<T, FocusEvent>;
  onInvalid?: JSX.EventHandlerUnion<T, Event>;
};

type Managed =
  | keyof Common<Control>
  | 'children'
  | 'maxlength'
  | 'readonly'
  | 'oninput'
  | 'onfocus'
  | 'onblur'
  | 'oninvalid'
  | 'aria-describedby'
  | 'aria-invalid';

export type TextFieldProps = Common<HTMLInputElement> &
  Omit<JSX.InputHTMLAttributes<HTMLInputElement>, Managed> & {
    multiline?: false;
  };

export type MultilineTextFieldProps = Common<HTMLTextAreaElement> &
  Omit<JSX.TextareaHTMLAttributes<HTMLTextAreaElement>, Managed> & {
    /** Textarea. Grows with its text unless `autoGrow` is false (text area: fixed `rows`, scrolls). */
    multiline: true;
    /** Visible lines. Default 1 for growing fields. */
    rows?: number;
    /** Default true. Prefer a fixed text area (`autoGrow={false}` + `rows`) on the web. */
    autoGrow?: boolean;
  };

type AnyProps = Common<Control> & {
  multiline?: boolean;
  rows?: number;
  autoGrow?: boolean;
};

const LOCAL = [
  'variant',
  'label',
  'supportingText',
  'errorText',
  'invalid',
  'errorIcon',
  'required',
  'disabled',
  'readOnly',
  'maxLength',
  'counter',
  'prefixText',
  'suffixText',
  'prefixLabel',
  'suffixLabel',
  'leading',
  'trailing',
  'clearable',
  'clearLabel',
  'value',
  'defaultValue',
  'onValueChange',
  'dense',
  'id',
  'class',
  'style',
  'ref',
  'onInput',
  'onFocus',
  'onBlur',
  'onInvalid',
  'multiline',
  'rows',
  'autoGrow',
] as const;

/** Calls a Solid handler prop, plain or bound (`[fn, data]`). */
const call = (handler: unknown, e: Event) => {
  if (typeof handler === 'function') handler(e);
  else if (Array.isArray(handler) && typeof handler[0] === 'function') handler[0](handler[1], e);
};

const present = (v: unknown) => v != null && v !== false && v !== '';

/**
 * M3 text field (m3-guidelines/components/text-fields.md): filled or
 * outlined, single-line or multi-line (growing or fixed text area), with
 * the floating label, leading/trailing icons or icon buttons, prefix and
 * suffix text, supporting/error text and a character counter. Built on Ark
 * UI `Field`, which wires the label, aria-describedby, aria-invalid and the
 * disabled/required/read-only attributes onto a native input.
 *
 * Errors: `errorText` (e.g. from the server) shows under the field and marks
 * it invalid. Native constraints (`required`, `pattern`, `type`, ...) show
 * the browser's validation message after the first blur following an edit,
 * or when the form is submitted / `reportValidity()` is called.
 */
export const TextField: Component<TextFieldProps | MultilineTextFieldProps> = (props) => {
  const [local, rest] = splitProps(props as AnyProps & Record<string, unknown>, LOCAL);
  const uid = createUniqueId();
  const counterId = `${uid}-counter`;
  const prefixId = `${uid}-prefix`;
  const suffixId = `${uid}-suffix`;

  let input!: Control;
  const controlled = () => local.value !== undefined;
  const initial = untrack(() => local.value ?? local.defaultValue ?? '');
  const [own, setOwn] = createSignal(initial);
  const text = () => (controlled() ? (local.value ?? '') : own());

  const [focused, setFocused] = createSignal(false);
  const [nativeError, setNativeError] = createSignal<string>();
  let edited = false;

  const errorMessage = () => (present(local.errorText) ? local.errorText : nativeError());
  const invalid = () => local.invalid ?? present(errorMessage());
  const floated = () => focused() || text().length > 0;
  const showCounter = () => local.counter && local.maxLength != null;

  const leading = resolveChildren(() => local.leading);
  const trailing = resolveChildren(() => local.trailing);
  const has = (c: () => unknown) => {
    const v = c();
    return Array.isArray(v) ? v.length > 0 : v != null && v !== false;
  };
  const showErrorIcon = () => !has(trailing) && invalid() && local.errorIcon !== false;
  const showClear = () =>
    !has(trailing) &&
    !showErrorIcon() &&
    local.clearable &&
    !local.disabled &&
    !local.readOnly &&
    text().length > 0;
  const hasTrailing = () => has(trailing) || showErrorIcon() || showClear();

  const validate = () =>
    setNativeError(input.validity.valid ? undefined : input.validationMessage || undefined);

  const onInput = (e: InputEvent) => {
    const value = (e.currentTarget as Control).value;
    edited = true;
    if (!controlled()) setOwn(value);
    if (nativeError()) validate();
    call(local.onInput, e);
    local.onValueChange?.(value);
  };

  const onFocus = (e: FocusEvent) => {
    setFocused(true);
    call(local.onFocus, e);
  };

  const onBlur = (e: FocusEvent) => {
    setFocused(false);
    if (edited) validate();
    call(local.onBlur, e);
  };

  // Show the message here instead of the browser bubble. Fired on submit,
  // checkValidity() and reportValidity().
  const onInvalid = (e: Event) => {
    e.preventDefault();
    setNativeError(input.validationMessage || undefined);
    const active = document.activeElement;
    if (!active || !active.matches(':invalid')) input.focus();
    call(local.onInvalid, e);
  };

  const clear = () => {
    input.value = '';
    input.dispatchEvent(new Event('input', { bubbles: true }));
    input.focus();
  };

  // Clicks on the container's padding focus the input.
  const onContainerDown = (e: MouseEvent) => {
    const target = e.target as Element;
    if (target === input || target.closest('button, a, input, textarea, select, label')) return;
    e.preventDefault();
    input.focus();
  };

  onMount(() => {
    // The browser may restore a value (back/forward cache, autofill).
    if (!controlled() && input.value !== own()) setOwn(input.value);
    const form = input.form;
    if (!form) return;
    const onReset = () =>
      setTimeout(() => {
        edited = false;
        setNativeError(undefined);
        if (!controlled()) setOwn(input.value);
      });
    form.addEventListener('reset', onReset);
    onCleanup(() => form.removeEventListener('reset', onReset));
  });

  const setRef = (el: Control) => {
    input = el;
    if (typeof local.ref === 'function') (local.ref as (el: Control) => void)(el);
  };

  const describedBy = (fromField: string | undefined) =>
    [
      fromField,
      local.prefixText ? prefixId : undefined,
      local.suffixText ? suffixId : undefined,
      showCounter() ? counterId : undefined,
    ]
      .filter(Boolean)
      .join(' ') || undefined;

  const labelText = () => (
    <>
      {local.label}
      <Show when={local.required}>
        <span class={styles.asterisk}>*</span>
      </Show>
    </>
  );

  return (
    <Field.Root
      id={local.id}
      class={local.class ? `${styles.root} ${local.class}` : styles.root}
      style={local.style}
      invalid={invalid()}
      disabled={local.disabled}
      readOnly={local.readOnly}
      required={local.required}
      data-variant={local.variant ?? 'filled'}
      data-floated={floated() ? '' : undefined}
      data-focused={focused() ? '' : undefined}
      data-label={local.label ? '' : undefined}
      data-leading={has(leading) ? '' : undefined}
      data-trailing={hasTrailing() ? '' : undefined}
      data-multiline={local.multiline ? '' : undefined}
      data-dense={local.dense ? '' : undefined}
    >
      <div
        class={styles.field}
        data-disabled={local.disabled ? '' : undefined}
        onMouseDown={onContainerDown}
      >
        <Show when={has(leading)}>
          <span class={styles.leading}>{leading()}</span>
        </Show>

        <Show when={local.label}>
          <Field.Label class={styles.label}>{labelText()}</Field.Label>
        </Show>

        <div class={styles.body}>
          <Show when={local.prefixText}>
            <span id={prefixId} class={styles.prefix} aria-label={local.prefixLabel}>
              {local.prefixText}
            </span>
          </Show>
          <Field.Context>
            {(field) => (
              <Show
                when={local.multiline}
                fallback={
                  <Field.Input
                    {...rest}
                    ref={setRef}
                    class={styles.input}
                    value={controlled() ? local.value : initial}
                    maxLength={local.maxLength}
                    aria-describedby={describedBy(field().ariaDescribedby)}
                    onInput={onInput}
                    onFocus={onFocus}
                    onBlur={onBlur}
                    onInvalid={onInvalid}
                  />
                }
              >
                <Field.Textarea
                  {...rest}
                  ref={setRef}
                  class={styles.input}
                  value={controlled() ? local.value : initial}
                  maxLength={local.maxLength}
                  rows={local.rows ?? 1}
                  autoresize={local.autoGrow ?? true}
                  aria-describedby={describedBy(field().ariaDescribedby)}
                  onInput={onInput}
                  onFocus={onFocus}
                  onBlur={onBlur}
                  onInvalid={onInvalid}
                />
              </Show>
            )}
          </Field.Context>
          <Show when={local.suffixText}>
            <span id={suffixId} class={styles.suffix} aria-label={local.suffixLabel}>
              {local.suffixText}
            </span>
          </Show>
        </div>

        <Show when={hasTrailing()}>
          <span class={styles.trailing}>
            <Switch>
              <Match when={has(trailing)}>{trailing()}</Match>
              <Match when={showErrorIcon()}>
                <Icon name="error" filled />
              </Match>
              <Match when={showClear()}>
                <IconButton
                  color="standard"
                  icon="cancel"
                  label={local.clearLabel ?? 'Clear'}
                  onClick={clear}
                />
              </Match>
            </Switch>
          </span>
        </Show>

        <Show
          when={(local.variant ?? 'filled') === 'outlined'}
          fallback={<span class={styles.indicator} aria-hidden="true" />}
        >
          <span class={styles.outline} aria-hidden="true">
            <span class={styles.outlineStart} />
            <Show when={local.label}>
              <span class={styles.notch}>
                <span class={styles.notchLabel}>{labelText()}</span>
              </span>
            </Show>
            <span class={styles.outlineEnd} />
          </span>
        </Show>
      </div>

      <Show when={present(local.supportingText) || (invalid() && present(errorMessage())) || showCounter()}>
        <div class={styles.footer}>
          <Show
            when={invalid() && present(errorMessage())}
            fallback={
              <Show when={present(local.supportingText)}>
                <Field.HelperText class={styles.supporting}>{local.supportingText}</Field.HelperText>
              </Show>
            }
          >
            <Field.ErrorText class={styles.supporting} role="alert">
              {errorMessage()}
            </Field.ErrorText>
          </Show>
          <Show when={showCounter()}>
            <span id={counterId} class={styles.counter}>
              <span class={styles.visuallyHidden}>Character count, </span>
              {text().length}/{local.maxLength}
            </span>
          </Show>
        </div>
      </Show>
    </Field.Root>
  );
};
